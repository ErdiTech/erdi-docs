"""Build JS test fixtures + per-model wire table from the published erdi-lrf Python package.

Source of truth for frame parsing is erdi-lrf 0.1.4 (PyPI, MIT).  The JS port in
src/lib/erdi-protocol.mjs is tested against golden frames generated here, plus frames
reconstructed from two real factory capture logs (fixtures/*.txt).

    python -I scripts/make_fixtures.py
"""
import json, os, re, sys, glob
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, glob.glob(os.path.join(ROOT, "vendor", "erdi_lrf-*.whl"))[0])
from erdi_lrf import models as M, protocol_a as pa, protocol_b as pb  # noqa: E402

KB = json.load(open(os.path.join(os.environ.get("ERDI_KB_DIR", "D:/erdi-kb"), "api", "kb.json"), encoding="utf-8"))
kb_models = {m["model"]: m for m in KB["models"]}
# Public-protocol set: KB family A/B with every wire field resolved (no unresolved frame/scale/status).
HOLD = {"SPD1200D03", "SPD1200S2G"}
PUBLIC = [m for m, v in kb_models.items()
          if v["protocol"]["family"] in ("A", "B") and m not in HOLD]
assert len(PUBLIC) == 22, len(PUBLIC)

out = {}
for name in PUBLIC:
    s = M.MODELS[name]
    out[name] = dict(
        family=s.family, default_baud=s.default_baud, frame_len=s.frame_len,
        distance_bytes=s.distance_bytes, unit=s.unit, raw_scale=s.raw_scale,
        out_of_range_raw=s.out_of_range_raw, min_range_m=s.min_range_m,
        max_range_m=s.max_range_m, a1_continuous_hold=bool(s.continuous_hold),
        start_stop=bool(s.supports(M.CAP_START_STOP)),
        metres_per_count=s.metres_per_count,
    )
HDR = "// generated by scripts/make_fixtures.py from erdi-lrf 0.1.4 + KB; do not edit" + chr(10)
open(os.path.join(ROOT, "src", "lib", "models.generated.mjs"), "w").write(HDR + "export default " + json.dumps(out, indent=1) + ";" + chr(10))

frames = []
def b_case(name, raw, note):
    s = M.MODELS[name]
    f = pb.build_data_frame(raw, s)
    m = pb.parse_data_frame(f, s)
    frames.append(dict(model=name, family="B", hex=f.hex(" "), note=note,
                       expect=dict(raw=m.raw, metres=m.metres, oor=m.out_of_range)))
for name in PUBLIC:
    s = M.MODELS[name]
    if s.family == "B":
        for raw in (0, 1, 4354 if s.distance_bytes == 2 else 200962, 12345):
            b_case(name, raw, "round-trip")
        b_case(name, s.out_of_range_raw, "out-of-range marker")
    else:
        for raw in (0, 123, 1234, 30000):
            body = bytes([0x55, 0xAA, 0x88, 0x01, 0xFF, raw >> 8, raw & 0xFF])
            f = body + bytes([pa.rx_checksum(body)])
            m = pa.parse_measurement(f, s)
            frames.append(dict(model=name, family="A", hex=f.hex(" "), note="single-shot reply",
                               expect=dict(raw=m.raw, metres=m.metres, status=m.status)))
# failure status
s = M.MODELS["LRF3000A1"]
body = bytes([0x55, 0xAA, 0x88, 0x00, 0xFF, 0, 0]); f = body + bytes([pa.rx_checksum(body)])
m = pa.parse_measurement(f, s, verify_checksum=True)
frames.append(dict(model="LRF3000A1", family="A", hex=f.hex(" "), note="STA=0 failure",
                   expect=dict(raw=m.raw, metres=m.metres, status=m.status)))

# Real factory captures (decoded values logged by the vendor tool).  Raw bytes are
# reconstructed from the logged value, so this checks unit scaling, not wire noise.
def read_cap(fn):
    return [int(l.split("]")[1]) for l in open(os.path.join(ROOT, "fixtures", fn)) if "]" in l]
cap = {}
for fn, model in (("lrf22vb-tool-capture-mm.txt", "LRF22VB"), ("lrf50h-tool-capture-cm.txt", "LRF50H")):
    vals = read_cap(fn)
    s = M.MODELS[model]
    cap[model] = dict(file=fn, frames=len(vals), min=min(vals), max=max(vals),
                      sample=[vals[0], vals[len(vals)//2], vals[-1]] + sorted(set(vals))[-3:])
    for v in cap[model]["sample"]:
        f = pb.build_data_frame(v, s); m = pb.parse_data_frame(f, s)
        frames.append(dict(model=model, family="B", hex=f.hex(" "), note=f"capture {fn} value {v}",
                           expect=dict(raw=m.raw, metres=m.metres, oor=m.out_of_range)))
# bad checksum + resync buffer
s = M.MODELS["LRF22VB"]
good = pb.build_data_frame(1709, s)
bad = bytes(good[:-1]) + bytes([good[-1] ^ 0xFF])
stream = b"\x00\x5c" + good + bad + good + b"\xff" + good[:2]
vals = [(i, f.hex(" ")) for i, f in pb.iter_data_frames(stream, s)]
json.dump(dict(frames=frames, captures=cap, bad_checksum=bad.hex(" "),
               resync=dict(model="LRF22VB", stream=stream.hex(" "),
                           valid=[h for _, h in vals]),
               a_stream=dict(model="LRF3000A1",
                   stream=(b"\x01\x02" + bytes.fromhex("55 aa 88 01 ff 00 7b 06") + b"\x55\xaa\x88\x01\xff\x00\x7b\x00" + bytes.fromhex("55 aa 88 01 ff 04 d2 e9")).hex(" "),
                   valid=[h.hex(" ") for h in pa.find_frames(b"\x01\x02" + bytes.fromhex("55 aa 88 01 ff 00 7b 06") + b"\x55\xaa\x88\x01\xff\x00\x7b\x00" + bytes.fromhex("55 aa 88 01 ff 04 d2 e9"))])),
          open(os.path.join(ROOT, "fixtures", "frames.json"), "w"), indent=1)
print("models", len(out), "frames", len(frames), "captures", {k: (v['frames'], v['min'], v['max']) for k, v in cap.items()})
